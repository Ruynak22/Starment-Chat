/* ---------- Trạng thái ---------- */
let currentLang = "vi";

function readStoredLanguage() {
  try {
    const s = JSON.parse(localStorage.getItem(SETTINGS_KEY) || "{}");
    if (s && SUPPORTED_LANGUAGES.some((l) => l.code === s.language)) return s.language;
  } catch { /* ignore */ }
  return "vi";
}

export function getCurrentLanguage() {
  return currentLang;
}

/** Dịch một khoá sang ngôn ngữ hiện tại (dự phòng sang tiếng Anh). */
export function t(key, fallbackOrVars, vars) {
  // Hỗ trợ cả t(key, {vars}) và t(key, "fallback", {vars}).
  const fallback = typeof fallbackOrVars === "string" ? fallbackOrVars : undefined;
  const params = typeof fallbackOrVars === "object" && fallbackOrVars !== null
    ? fallbackOrVars
    : vars;
  let text = (DICTS[currentLang] && DICTS[currentLang][key])
    ?? DICTS.en[key]
    ?? fallback
    ?? key;
  if (params) {
    Object.keys(params).forEach((k) => {
      text = text.split(`{${k}}`).join(String(params[k]));
    });
  }
  return text;
}

/** Áp dụng bản dịch cho mọi phần tử có data-i18n trong DOM. */
export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.documentElement.lang = currentLang;
  document.documentElement.dataset.lang = currentLang;
}

/** Đổi ngôn ngữ hiện tại (không tự lưu — settings.js lo việc lưu). */
export function setLanguage(code) {
  currentLang = SUPPORTED_LANGUAGES.some((l) => l.code === code) ? code : "vi";
  applyTranslations();
  window.dispatchEvent(new CustomEvent("i18n:changed", { detail: { language: currentLang } }));
}

export function initI18n() {
  currentLang = readStoredLanguage();
  applyTranslations();
  window.addEventListener("settings:changed", (e) => {
    if (e.detail?.key === "language") setLanguage(e.detail.value);
  });
}
